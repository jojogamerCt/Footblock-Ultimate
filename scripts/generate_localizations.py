def main() -> None:
    english_path = LANG_DIR / "en_us.json"
    english = json.loads(english_path.read_text(encoding="utf-8"))
    keys = list(english)

    for locale, values in TRANSLATIONS.items():
        if len(values) != len(keys):
            raise ValueError(f"{locale}: expected {len(keys)} values, found {len(values)}")
        localized = dict(zip(keys, values, strict=True))
        for key, source in english.items():
            if sorted(PLACEHOLDER.findall(source)) != sorted(PLACEHOLDER.findall(localized[key])):
                raise ValueError(f"{locale}: placeholders differ for {key}")
        target = LANG_DIR / f"{locale}.json"
        target.write_text(json.dumps(localized, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Generated {target.relative_to(LANG_DIR.parents[4])} ({len(localized)} keys)")

    print(f"Validated {len(TRANSLATIONS) + 1} complete locales with {len(keys)} keys each.")


if __name__ == "__main__":
    main()
